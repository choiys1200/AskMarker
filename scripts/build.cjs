'use strict';
// Static CommonJS bundle for MV3 content scripts. No eval, dependencies or network.
// Only literal relative require() calls inside src/ are supported intentionally.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),src=path.join(root,'src'),modules=new Map();
function visit(file){
  file=path.resolve(file);
  if(!file.startsWith(src+path.sep))throw Error('Module escapes src: '+file);
  const id=path.relative(src,file).split(path.sep).join('/');
  if(modules.has(id))return id;
  modules.set(id,null);
  const raw=fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n');
  let code;
  if(file.endsWith('.js')){
    code=raw.replace(/require\(['"](\.[^'"]+)['"]\)/g,(_,ref)=>{
      const next=path.resolve(path.dirname(file),path.extname(ref)?ref:ref+'.js');
      return 'require('+JSON.stringify(visit(next))+')';
    });
    new vm.Script('(function(module,exports,require){\n'+code+'\n})',{filename:file});
  }else if(/\.(css|html)$/.test(file))code='module.exports='+JSON.stringify(raw)+';';
  else throw Error('Unsupported resource: '+file);
  modules.set(id,code);return id;
}
function build(entry,targetName){
modules.clear();visit(path.join(src,entry));
const version=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8')).version;
const output=`/* AskMarker ${version} ${targetName} — GENERATED by scripts/build.cjs. Edit src/, then npm run build. */
(()=>{'use strict';
const factories={
${[...modules].sort(([a],[b])=>a.localeCompare(b)).map(([id,code])=>JSON.stringify(id)+':function(module,exports,require){\n'+code+'\n}').join(',\n')}
};
const cache=Object.create(null);
function require(id){if(cache[id])return cache[id].exports;const module={exports:{}};cache[id]=module;factories[id](module,module.exports,require);return module.exports;}
require('${entry}');
})();
`.replaceAll('__ASKMARK_VERSION__',version);
const target=path.join(root,targetName);
if(process.argv.includes('--check')){
  if(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==output)throw Error('content.js is stale; run npm run build');
}else fs.writeFileSync(target,output);
console.log(`AskMarker ${version} ${targetName}: ${modules.size} modules, reproducible bundle ${process.argv.includes('--check')?'verified':'built'}.`);

}
build('app.js','content.js');
build('background.js','background.js');
